"""
Mock Agent Implementation
=========================

Mock LLM agent for testing and development purposes.
"""

from __future__ import annotations

import asyncio
import random
import time
import uuid
from typing import Any

from loguru import logger

from art_framework.agents.base import (
    Agent,
    AgentConfig,
    AgentResponse,
    Critique,
)


class MockAgent(Agent):
    """
    Mock agent for testing the ART framework without real LLM API calls.
    
    Generates deterministic or randomized responses based on configuration.
    Useful for:
    - Unit testing
    - Integration testing
    - Performance benchmarking
    - Development without API costs
    """
    
    def __init__(
        self,
        config: AgentConfig,
        response_quality: float = 0.75,
        latency_range: tuple[float, float] = (0.1, 0.5),
        deterministic: bool = False,
    ) -> None:
        """
        Initialize the mock agent.
        
        Args:
            config: Agent configuration
            response_quality: Base quality level (0-1) for generated responses
            latency_range: Min/max latency in seconds for simulated API calls
            deterministic: If True, use deterministic responses based on query hash
        """
        super().__init__(config)
        self.response_quality = response_quality
        self.latency_range = latency_range
        self.deterministic = deterministic
        self._response_templates = [
            "Based on the analysis of '{query}', the answer involves considering "
            "multiple factors including context, accuracy, and relevance.",
            "The query '{query}' requires a comprehensive approach. Key points "
            "include: 1) Understanding the context, 2) Evaluating evidence, "
            "3) Drawing logical conclusions.",
            "Addressing '{query}': After careful consideration, the most accurate "
            "response incorporates both theoretical understanding and practical "
            "application of the concepts involved.",
            "For '{query}', it's important to consider various perspectives. "
            "The evidence suggests a nuanced approach that balances multiple "
            "factors for an optimal outcome.",
            "Regarding '{query}': A thorough examination reveals that the answer "
            "depends on several interconnected factors. The optimal response "
            "takes into account current best practices and established principles.",
        ]
    
    async def initialize(self) -> None:
        """Initialize the mock agent."""
        if self._is_initialized:
            return
        
        # Simulate initialization delay
        await asyncio.sleep(0.1)
        self._is_initialized = True
        logger.info(f"Mock agent '{self.name}' initialized")
    
    async def generate_response(
        self,
        query: str,
        query_id: str,
        context: dict[str, Any] | None = None,
    ) -> AgentResponse:
        """Generate a mock response to the query."""
        start_time = time.time()
        
        # Simulate API latency
        latency = random.uniform(*self.latency_range)
        await asyncio.sleep(latency)
        
        # Select response template
        if self.deterministic:
            template_idx = hash(query) % len(self._response_templates)
        else:
            template_idx = random.randint(0, len(self._response_templates) - 1)
        
        template = self._response_templates[template_idx]
        content = template.format(query=query[:50])
        
        # Add agent-specific flavor
        content += f"\n\n[Response generated by {self.name}]"
        
        # Calculate confidence based on quality setting
        quality_variance = 0.1 if self.deterministic else random.uniform(-0.15, 0.15)
        confidence = min(1.0, max(0.0, self.response_quality + quality_variance))
        
        self.state.total_queries += 1
        self.add_to_context({"role": "user", "content": query})
        self.add_to_context({"role": "assistant", "content": content})
        
        latency_ms = (time.time() - start_time) * 1000
        
        return AgentResponse(
            agent_id=self.id,
            query_id=query_id,
            content=content,
            confidence=confidence,
            reasoning=f"Mock response from {self.config.model_name}",
            metadata={
                "model": self.config.model_name,
                "mock": True,
                "quality_setting": self.response_quality,
            },
            latency_ms=latency_ms,
        )
    
    async def critique_response(
        self,
        original_query: str,
        target_response: AgentResponse,
        context: dict[str, Any] | None = None,
    ) -> Critique:
        """Generate a mock critique of another agent's response."""
        # Simulate critique latency
        await asyncio.sleep(random.uniform(*self.latency_range))
        
        # Generate scores with some variance
        base_score = self.response_quality * 100
        variance = 20 if self.deterministic else random.uniform(-20, 20)
        
        accuracy = min(100, max(0, base_score + random.uniform(-10, 10)))
        coherence = min(100, max(0, base_score + random.uniform(-10, 10)))
        completeness = min(100, max(0, base_score + random.uniform(-10, 10)))
        relevance = min(100, max(0, base_score + random.uniform(-10, 10)))
        overall = (accuracy + coherence + completeness + relevance) / 4 + variance / 4
        overall = min(100, max(0, overall))
        
        pros = [
            "Clear and structured presentation",
            "Addresses the main question directly",
            "Good use of supporting evidence",
        ]
        
        cons = [
            "Could provide more specific examples",
            "Some points need further elaboration",
        ]
        
        suggestions = [
            "Consider adding concrete examples",
            "Expand on the key implications",
        ]
        
        self.state.total_critiques_given += 1
        
        return Critique(
            critic_agent_id=self.id,
            target_agent_id=target_response.agent_id,
            response_id=str(uuid.uuid4()),
            score=overall,
            accuracy_score=accuracy,
            coherence_score=coherence,
            completeness_score=completeness,
            relevance_score=relevance,
            pros=pros[:2],
            cons=cons[:2],
            suggestions=suggestions[:2],
            reasoning=f"Mock critique by {self.name} with quality setting {self.response_quality}",
        )
    
    async def improve_response(
        self,
        original_response: AgentResponse,
        critiques: list[Critique],
    ) -> AgentResponse:
        """Improve a response based on received critiques."""
        await asyncio.sleep(random.uniform(*self.latency_range))
        
        # Calculate improvement factor based on critiques
        avg_score = sum(c.score for c in critiques) / len(critiques) if critiques else 70
        improvement_factor = (100 - avg_score) / 200  # Small improvement
        
        improved_content = (
            f"{original_response.content}\n\n"
            f"[IMPROVED VERSION]\n"
            f"Based on {len(critiques)} critiques received, this response has been "
            f"enhanced to address the feedback provided. Key improvements include:\n"
            f"- Enhanced clarity and structure\n"
            f"- Additional supporting details\n"
            f"- Better alignment with the original query"
        )
        
        return AgentResponse(
            agent_id=self.id,
            query_id=original_response.query_id,
            content=improved_content,
            confidence=min(0.95, original_response.confidence + improvement_factor),
            reasoning="Improved based on peer critiques (mock)",
            metadata={
                "model": self.config.model_name,
                "mock": True,
                "critiques_incorporated": len(critiques),
            },
            latency_ms=random.uniform(*self.latency_range) * 1000,
        )
