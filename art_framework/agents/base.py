"""
Base Agent Module
=================

Defines the abstract base class for all LLM agents in the ART framework.
"""

from __future__ import annotations

import uuid
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Any


class CritiqueStrategy(str, Enum):
    """Strategies for critiquing other agents' responses."""
    
    FACT_CHECK = "fact_check"
    LOGIC_EVALUATION = "logic_evaluation"
    PROS_CONS = "pros_cons"
    COMPREHENSIVE = "comprehensive"


@dataclass
class AgentConfig:
    """Configuration for an LLM agent."""
    
    name: str
    model_name: str
    temperature: float = 0.7
    max_tokens: int = 2048
    critique_strategy: CritiqueStrategy = CritiqueStrategy.COMPREHENSIVE
    api_key: str | None = None
    base_url: str | None = None
    timeout: float = 60.0
    
    def __post_init__(self) -> None:
        """Validate configuration after initialization."""
        if not 0.0 <= self.temperature <= 2.0:
            raise ValueError("Temperature must be between 0.0 and 2.0")
        if self.max_tokens < 1:
            raise ValueError("max_tokens must be positive")


@dataclass
class AgentState:
    """Internal state maintained by an agent across rounds."""
    
    agent_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    context_history: list[dict[str, Any]] = field(default_factory=list)
    elo_score: float = 1500.0
    wins: int = 0
    losses: int = 0
    draws: int = 0
    total_queries: int = 0
    total_critiques_given: int = 0
    total_critiques_received: int = 0
    performance_metrics: dict[str, float] = field(default_factory=dict)
    llm_calls: int = 0
    prompt_tokens: int = 0
    completion_tokens: int = 0
    cost_usd: float = 0.0
    created_at: datetime = field(default_factory=datetime.utcnow)
    last_active: datetime = field(default_factory=datetime.utcnow)
    
    @property
    def win_rate(self) -> float:
        """Calculate win rate."""
        total = self.wins + self.losses + self.draws
        return self.wins / total if total > 0 else 0.0
    
    @property
    def total_matches(self) -> int:
        """Get total number of matches played."""
        return self.wins + self.losses + self.draws
    
    def update_activity(self) -> None:
        """Update last active timestamp."""
        self.last_active = datetime.utcnow()


@dataclass
class AgentResponse:
    """Response generated by an agent."""
    
    agent_id: str
    query_id: str
    content: str
    confidence: float
    reasoning: str | None = None
    metadata: dict[str, Any] = field(default_factory=dict)
    timestamp: datetime = field(default_factory=datetime.utcnow)
    latency_ms: float = 0.0


@dataclass
class Critique:
    """Critique of another agent's response."""
    
    critic_agent_id: str
    target_agent_id: str
    response_id: str
    score: float  # 0-100
    accuracy_score: float
    coherence_score: float
    completeness_score: float
    relevance_score: float
    pros: list[str] = field(default_factory=list)
    cons: list[str] = field(default_factory=list)
    suggestions: list[str] = field(default_factory=list)
    reasoning: str = ""
    timestamp: datetime = field(default_factory=datetime.utcnow)
    usage: dict[str, Any] = field(default_factory=dict)


class Agent(ABC):
    """
    Abstract base class for LLM agents in the ART framework.
    
    Each agent can:
    - Receive queries and generate independent responses
    - Critique and counter-argue other agents' responses
    - Maintain internal knowledge state for context-aware reasoning
    - Track performance metrics per query and overall
    """
    
    def __init__(self, config: AgentConfig) -> None:
        """
        Initialize the agent with configuration.
        
        Args:
            config: Agent configuration settings
        """
        self.config = config
        self.state = AgentState()
        self._is_initialized = False
    
    @property
    def id(self) -> str:
        """Get agent's unique identifier."""
        return self.state.agent_id
    
    @property
    def name(self) -> str:
        """Get agent's name."""
        return self.config.name
    
    @property
    def elo_score(self) -> float:
        """Get agent's current ELO score."""
        return self.state.elo_score
    
    @elo_score.setter
    def elo_score(self, value: float) -> None:
        """Set agent's ELO score."""
        self.state.elo_score = value
    
    @abstractmethod
    async def initialize(self) -> None:
        """Initialize the agent and verify connectivity."""
        pass
    
    @abstractmethod
    async def generate_response(
        self,
        query: str,
        query_id: str,
        context: dict[str, Any] | None = None,
    ) -> AgentResponse:
        """
        Generate a response to the given query.
        
        Args:
            query: The input query/task
            query_id: Unique identifier for the query
            context: Optional context from previous rounds
            
        Returns:
            AgentResponse containing the generated response
        """
        pass
    
    @abstractmethod
    async def critique_response(
        self,
        original_query: str,
        target_response: AgentResponse,
        context: dict[str, Any] | None = None,
    ) -> Critique:
        """
        Critique another agent's response.
        
        Args:
            original_query: The original query/task
            target_response: The response to critique
            context: Optional context from previous rounds
            
        Returns:
            Critique containing evaluation and feedback
        """
        pass
    
    @abstractmethod
    async def improve_response(
        self,
        original_response: AgentResponse,
        critiques: list[Critique],
    ) -> AgentResponse:
        """
        Improve a response based on received critiques.
        
        Args:
            original_response: The original response to improve
            critiques: List of critiques received from other agents
            
        Returns:
            Improved AgentResponse
        """
        pass
    
    def add_to_context(self, entry: dict[str, Any]) -> None:
        """
        Add an entry to the agent's context history.
        
        Args:
            entry: Context entry to add
        """
        self.state.context_history.append({
            **entry,
            "timestamp": datetime.utcnow().isoformat(),
        })
        self.state.update_activity()
    
    def clear_context(self) -> None:
        """Clear the agent's context history."""
        self.state.context_history.clear()
    
    def update_metrics(self, metrics: dict[str, float]) -> None:
        """
        Update performance metrics.
        
        Args:
            metrics: Dictionary of metric updates
        """
        for key, value in metrics.items():
            if key in self.state.performance_metrics:
                self.state.performance_metrics[key] = (
                    self.state.performance_metrics[key] * 0.9 + value * 0.1
                )
            else:
                self.state.performance_metrics[key] = value
    
    def record_win(self) -> None:
        """Record a win for the agent."""
        self.state.wins += 1
        self.state.update_activity()
    
    def record_loss(self) -> None:
        """Record a loss for the agent."""
        self.state.losses += 1
        self.state.update_activity()
    
    def record_draw(self) -> None:
        """Record a draw for the agent."""
        self.state.draws += 1
        self.state.update_activity()
    
    def to_dict(self) -> dict[str, Any]:
        """Convert agent to dictionary representation."""
        return {
            "id": self.id,
            "name": self.name,
            "model_name": self.config.model_name,
            "elo_score": self.elo_score,
            "wins": self.state.wins,
            "losses": self.state.losses,
            "draws": self.state.draws,
            "win_rate": self.state.win_rate,
            "total_queries": self.state.total_queries,
            "llm_calls": self.state.llm_calls,
            "prompt_tokens": self.state.prompt_tokens,
            "completion_tokens": self.state.completion_tokens,
            "cost_usd": self.state.cost_usd,
            "created_at": self.state.created_at.isoformat(),
            "last_active": self.state.last_active.isoformat(),
        }
